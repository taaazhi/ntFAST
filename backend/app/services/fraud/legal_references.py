from __future__ import annotations

from dataclasses import dataclass
from typing import Dict


@dataclass(frozen=True)
class LegalArticle:
    """Статья нормативного акта РК."""

    code: str
    number: str
    title: str
    source_url: str

    def cite(self) -> str:
        """Ссылка в том виде, в каком она уходит в отчёт."""
        return f"{self.code} ст. {self.number} ({self.title.lower()})"


