"""Отличить сторону сделки от описания самой операции.

Банк кладёт в поле контрагента что попало. Рядом с «ТОО Астана Строй» там
оказывается «Комиссия за перевод на карту др. банка», «Transaction Fee» или
«Басқакартағааударым» — это не тот, кому платят, а то, что произошло.

Почему это важнее, чем кажется. Такие строки становятся узлами в графе
контрагентов: система показывает следователю, что человек 60 раз переводил
деньги «Комиссии», и считает её значимой связью. Схемы вывода средств ищут
именно в этом графе, и мусорные узлы в нём — не косметика.

Правило, а не модель, по той же причине, что и с ИП: локальная модель на
этих строках даёт 5 из 16, а признак здесь формальный — наличие слова об
операции при отсутствии признаков юридического лица. Где ответ выводится
надёжно, модель не спрашивают.

Текст в выписках часто слипается («Transfertoanothercard»,
«Monthlyfeeforcardservice»), поэтому маркеры ищутся подстрокой в строке
без пробелов, а не словами.
"""
from __future__ import annotations

import re
from typing import Final

#: Латинская Ə (U+018F) вместо казахской Ә — так печатает Kaspi.
_SCHWA: Final = str.maketrans({"Ə": "Ә", "ə": "ә"})

#: Корни слов, обозначающих операцию, а не её участника. Приведены к форме
#: без окончаний, чтобы падежи и слипшийся текст не мешали.
OPERATION_MARKERS: Final = (
    # Комиссии. «fee» отдельным маркером быть не может: оно сидит внутри
    # «coffee», и три кофейни из набора попали в каналы.
    "комисси", "commission", "transactionfee", "withdrawfee", "servicefee",
    "regularcharge", "feeforcard", "feeisincluded",
    # переводы и зачисления
    "перевод", "transfer", "аударым", "аудару", "аударғаны", "картағааударым",
    "зачислен", "replenish", "толықтыру",
    # обмен и конвертация
    "конверт", "convert", "обменвалют",
    # каналы и техника. «самообслуживания» в одиночку не годится: автомойка
    # самообслуживания — обычный мерчант.
    "аппаратсамообслуживания", "банкомат", "терминалсамообслуживания",
    # внутренние операции бирж и кошельков
    "betweenspot", "betweenmain", "betweenum", "fundingwallet", "futuresaccount",
    "withdrawfeeisincluded", "binanceconvert",
    # назначение платежа вместо контрагента
    "жалақы",
)

#: Обороты, которые описывают канал даже при упоминании банка. «С карты
#: другого банка» — это способ пополнения, а не сторона сделки: банк здесь
#: назван неопределённо, в отличие от «Halyk Bank». Проверяются раньше
#: правовых форм, иначе слово «банк» внутри выдавало их за организацию.
CHANNEL_MARKERS: Final = (
    "скарты", "скартыдругого", "fromcard", "ofotherbank", "otherbanks",
    "картасынан", "басқабанк", "другогобанка", "накартудр", "anothercard",
)

#: Признаки того, что перед нами всё-таки организация: тогда слово об
#: операции внутри названия ничего не значит. «ТОО Транспортная компания»
#: содержит «транспорт», но остаётся контрагентом.
#:
#: Ищутся и в слипшемся виде: «Қаражаттыңшотқатүсуі АОФинансовый центр» —
#: это банк, к названию которого приклеилось описание операции, и без такой
#: проверки он уходил в каналы.
LEGAL_FORM_MARKERS: Final = (
    "тоо", "ао", "жшс", "ақ", "ип", "жк", "llp", "llc", "ltd",
    "товарищество", "акционерное", "филиал", "банк", "bank",
)

_NON_WORD = re.compile(r"[^а-яёәғқңөұүіһa-z0-9]+")


def _normalise(value: str) -> str:
    """Нижний регистр, казахская schwa, без пробелов и пунктуации."""
    lowered = (value or "").translate(_SCHWA).lower().replace("ё", "е")
    return _NON_WORD.sub("", lowered)


def _mentions_legal_form(raw: str) -> bool:
    """Есть ли в названии правовая форма.

    Проверяется двумя способами. Как отдельное слово — «ТОО Астана Строй»,
    «Halyk Bank». И как приклеенный префикс — «АОФинансовый центр»: в
    выписке текст слипается, и форма перестаёт быть словом, оставаясь
    признаком организации.
    """
    words = set(_NON_WORD.sub(" ", raw.lower()).split())
    if words & set(LEGAL_FORM_MARKERS):
        return True

    packed = _normalise(raw)
    return any(
        # Только с начала слова: иначе «ип» найдётся в «Interpay».
        part.startswith(marker) and len(part) > len(marker) + 2
        for marker in LEGAL_FORM_MARKERS
        for part in (packed,)
    )


def is_operation_description(name: str) -> bool:
    """«Комиссия за перевод» — да, «ТОО Астана Строй» — нет.

    Организации проверяются первыми: название юридического лица может
    содержать слово об операции, и тогда оно всё равно остаётся стороной
    сделки, а не её описанием.
    """
    raw = (name or "").strip()
    if not raw:
        return False

    packed = _normalise(raw)
    if not packed:
        return False

    # Обороты про «карту другого банка» решаются до проверки формы: слово
    # «банк» в них есть, но конкретного банка не названо.
    if any(marker in packed for marker in CHANNEL_MARKERS):
        return True

    if _mentions_legal_form(raw):
        return False

    return any(marker in packed for marker in OPERATION_MARKERS)
